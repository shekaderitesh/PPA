#include <iostream>
using namespace std;

int main() {
    short int a = 10;
    long int b = 100000;
    signed int c = -20;
    unsigned int d = 50;

    cout << "short = " << a << endl;
    cout << "long = " << b << endl;
    cout << "signed = " << c << endl;
    cout << "unsigned = " << d << endl;

    return 0;
}